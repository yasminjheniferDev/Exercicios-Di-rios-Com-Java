public class ParesDe1Ate50 {
    public static void main(String[] args) {

        //Laço imprimindo os números de 1 até 50 com a condição de que sejam números pares.K
        for (int cont = 1; cont <= 50; cont++) {
            if (cont % 2 == 0) {
                System.out.println(cont);

            }
        }

    }
}
